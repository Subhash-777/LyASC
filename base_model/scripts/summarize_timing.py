#!/usr/bin/env python3
"""
summarize_timing.py
Walks every results/logs/*.json and reconstructs elapsed wall-clock time from
the matching .log file's first and last timestamps.

Outputs:
  - results/review/timing_summary.md
  - A printed table for copy-paste into review notes.

Usage:
  python scripts/summarize_timing.py [--base_dir /path/to/base_model]
"""
import argparse
import glob
import json
import os
import re
from collections import defaultdict
from datetime import datetime

TIMESTAMP_RE = re.compile(
    r"^(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})\s+INFO",
)
ELAPSED_RE = re.compile(r"elapsed=(\d+)s")


def parse_log_timestamps(log_path):
    """Return (first_ts, last_ts, last_elapsed_s) from a .log file."""
    first_ts = last_ts = None
    last_elapsed = None
    try:
        with open(log_path, errors="replace") as f:
            for line in f:
                m = TIMESTAMP_RE.match(line)
                if m:
                    ts_str = m.group(1)
                    ts = datetime.strptime(ts_str, "%Y-%m-%d %H:%M:%S")
                    if first_ts is None:
                        first_ts = ts
                    last_ts = ts
                em = ELAPSED_RE.search(line)
                if em:
                    last_elapsed = int(em.group(1))
    except FileNotFoundError:
        pass
    return first_ts, last_ts, last_elapsed


def hms(seconds):
    if seconds is None:
        return "---"
    h = seconds // 3600
    m = (seconds % 3600) // 60
    s = seconds % 60
    return f"{h:02d}:{m:02d}:{s:02d}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--base_dir", default=".", help="Workspace root")
    args = parser.parse_args()

    log_dir = os.path.join(args.base_dir, "results", "logs")
    review_dir = os.path.join(args.base_dir, "results", "review")
    os.makedirs(review_dir, exist_ok=True)
    out_path = os.path.join(review_dir, "timing_summary.md")

    json_files = sorted(glob.glob(os.path.join(log_dir, "*.json")))

    rows = []
    by_table = defaultdict(list)
    grand_elapsed = 0

    for jf in json_files:
        with open(jf) as f:
            d = json.load(f)

        config = d.get("config_name", "")
        variant = d.get("variant_name", d.get("variant", ""))
        depth = d.get("depth", "")
        seed = d.get("seed", "")
        total_iters = d.get("total_iters", "")

        # Derive table label
        for tbl in ("table1", "table3", "table4", "table6"):
            if tbl in config:
                table_label = tbl.replace("table", "Table ")
                break
        else:
            table_label = config

        # Match to .log file — actual naming convention is __seed{N}.log (no depth in name)
        safe_var = variant.replace("+", "plus").replace("/", "_").replace(" ", "_")
        log_name = f"{config}__{safe_var}__seed{seed}.log"
        log_path = os.path.join(log_dir, log_name)

        first_ts, last_ts, elapsed_s = parse_log_timestamps(log_path)

        # Prefer the elapsed field from the log (most accurate: excludes pauses)
        if elapsed_s is None and first_ts and last_ts:
            elapsed_s = int((last_ts - first_ts).total_seconds())

        if elapsed_s:
            grand_elapsed += elapsed_s
            by_table[table_label].append(elapsed_s)

        rows.append({
            "table": table_label,
            "config": config,
            "variant": variant,
            "depth": depth,
            "seed": seed,
            "total_iters": total_iters,
            "elapsed_s": elapsed_s,
            "elapsed_hms": hms(elapsed_s),
        })

    # --- Print and write ---
    header = (
        f"{'Table':<10} {'Variant':<22} {'Depth':>5} {'Seed':>4} "
        f"{'Iters':>6} {'Elapsed':>10}"
    )
    sep = "-" * len(header)

    lines_out = [
        "# Training Timing Summary",
        "",
        f"Generated by `scripts/summarize_timing.py`.",
        f"Elapsed = wall-clock time read from `elapsed=Ns` fields in `.log` files.",
        f"GPU: NVIDIA GeForce RTX 3050 (4 GB).",
        "",
        "## Per-Run Times",
        "",
        f"```",
        header,
        sep,
    ]

    prev_table = None
    table_totals_lines = []
    for r in rows:
        if r["table"] != prev_table and prev_table is not None:
            total_s = sum(by_table[prev_table])
            lines_out.append(f"{'':>10} {'SUBTOTAL':>22} {'':>5} {'':>4} {'':>6} {hms(total_s):>10}")
            lines_out.append(sep)
        prev_table = r["table"]

        lines_out.append(
            f"{r['table']:<10} {r['variant']:<22} {str(r['depth']):>5} "
            f"{str(r['seed']):>4} {str(r['total_iters']):>6} {r['elapsed_hms']:>10}"
        )

    if prev_table:
        total_s = sum(by_table[prev_table])
        lines_out.append(f"{'':>10} {'SUBTOTAL':>22} {'':>5} {'':>4} {'':>6} {hms(total_s):>10}")

    lines_out += [
        sep,
        f"{'GRAND TOTAL':<10} {len(rows)} runs{' ':>30} {hms(grand_elapsed):>10}",
        "```",
        "",
        "## Per-Table Totals",
        "",
        "| Table | Runs | Total Wall-Clock |",
        "|-------|------|-----------------|",
    ]
    for tbl in sorted(by_table):
        s = sum(by_table[tbl])
        lines_out.append(f"| {tbl} | {len(by_table[tbl])} | {hms(s)} |")

    lines_out += [
        f"| **GRAND TOTAL** | **{len(rows)}** | **{hms(grand_elapsed)}** |",
        "",
        f"## Notes",
        "",
        "- Table 6 runs are significantly longer (~540 s/1k iters) than Tables 1/4 (~250 s/1k) because the 2rSkip+LN variant on CIFAR-100 with depth-110 is computationally heavier.",
        "- All runs used gradient clipping (`max_norm=5.0`) added post-hoc; earlier unclipped runs (before this fix) are not counted here.",
        "- Seeds 3 and 4 were configured in the YAMLs (for a planned 5-seed protocol) but were not executed — all tables use 3 seeds as confirmed in the FINAL CSVs.",
    ]

    content = "\n".join(lines_out)
    print(content)
    with open(out_path, "w") as f:
        f.write(content)
    print(f"\nWritten: {out_path}")


if __name__ == "__main__":
    main()
